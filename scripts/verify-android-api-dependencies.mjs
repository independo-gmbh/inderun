#!/usr/bin/env node
/**
 * Verifies the dependency scopes of the published Android POMs against a
 * committed baseline (`android/published-api-dependencies.txt`).
 *
 * This is the guard for the class of bug reported in
 * https://github.com/independo-gmbh/inderun/issues/189: a dependency whose types
 * appear in a module's public signatures declared as `implementation` rather than
 * `api`. Gradle keeps `implementation` dependencies off consumers' compile
 * classpath on purpose, and com.vanniktech.maven.publish maps them to POM
 * `runtime` scope, so the omission is invisible in this workspace and only breaks
 * for someone consuming the artifacts from Maven Central. Nothing in a normal
 * `./gradlew build` notices.
 *
 * The obvious tool for this is a full ABI check -- binary-compatibility-validator
 * or metalava -- and #189 asked for one. Neither works on this build: both hook
 * the `KotlinAndroidTarget` registered by the standalone `org.jetbrains.kotlin.android`
 * plugin, and AGP 9 refuses that plugin outright now that Kotlin support is built in
 * ("no longer required for Kotlin support since AGP 9.0"). BCV applies cleanly and
 * then registers no tasks at all. So this checks the published metadata instead,
 * which is narrower than an ABI dump but covers the actual regression: the moment
 * an `api(...)` edge turns back into `implementation(...)`, the scope in the POM
 * flips and this fails.
 *
 * Usage:
 *   node scripts/verify-android-api-dependencies.mjs            # verify
 *   node scripts/verify-android-api-dependencies.mjs --update   # rewrite the baseline
 *   node scripts/verify-android-api-dependencies.mjs --no-generate  # reuse existing POMs
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const androidRoot = join(repoRoot, "android");
const baselinePath = join(androidRoot, "published-api-dependencies.txt");

const update = process.argv.includes("--update");
const skipGenerate = process.argv.includes("--no-generate");

const BASELINE_HEADER = `# Dependency scopes of the published Android POMs, as generated by
# com.vanniktech.maven.publish from each module's build.gradle.kts.
#
#   compile -> declared api(...)         -> on consumers' compile classpath
#   runtime -> declared implementation(...) -> NOT on consumers' compile classpath
#
# A dependency whose types appear in a module's public signatures MUST be compile.
# Regenerate after an intentional change with:
#
#   node scripts/verify-android-api-dependencies.mjs --update
#
# See scripts/verify-android-api-dependencies.mjs for why this exists rather than
# a full ABI dump, and https://github.com/independo-gmbh/inderun/issues/189.
`;

function fail(message) {
  console.error(`\n❌ ${message}\n`);
  process.exit(1);
}

/** Modules that apply com.vanniktech.maven.publish, i.e. the ones that ship. */
function publishedModules() {
  return readdirSync(androidRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => {
      const buildFile = join(androidRoot, name, "build.gradle.kts");
      return (
        existsSync(buildFile) &&
        readFileSync(buildFile, "utf8").includes("com.vanniktech.maven.publish")
      );
    })
    .sort();
}

function generatePoms() {
  const gradlew = join(androidRoot, "gradlew");
  const result = spawnSync(gradlew, ["generatePomFileForMavenPublication", "-q"], {
    cwd: androidRoot,
    stdio: "inherit"
  });
  if (result.status !== 0) {
    fail(
      "Could not generate the Maven POMs. Run `cd android && ./gradlew generatePomFileForMavenPublication` to see why."
    );
  }
}

/**
 * Pulls `<dependency>` blocks out of a POM. Deliberately a regex rather than a
 * dependency on an XML parser: the input is a file Gradle just wrote from a fixed
 * template, not arbitrary XML.
 */
function readScopes(module) {
  const pomPath = join(androidRoot, module, "build", "publications", "maven", "pom-default.xml");
  if (!existsSync(pomPath)) {
    fail(`No generated POM for :${module} at ${pomPath}. Run without --no-generate.`);
  }
  const pom = readFileSync(pomPath, "utf8");
  const entries = [];
  for (const block of pom.matchAll(/<dependency>([\s\S]*?)<\/dependency>/g)) {
    const field = (name) => block[1].match(new RegExp(`<${name}>(.*?)</${name}>`))?.[1];
    const groupId = field("groupId");
    const artifactId = field("artifactId");
    const scope = field("scope") ?? "compile";
    if (!groupId || !artifactId) {
      fail(`Malformed <dependency> in :${module}'s POM.`);
    }
    entries.push(`${module} ${scope} ${groupId}:${artifactId}`);
  }
  // Sorted so the baseline diff reflects a real scope change, not Gradle's
  // resolution order, which is not stable across versions.
  return entries.sort();
}

function collect() {
  return publishedModules().flatMap(readScopes);
}

if (!skipGenerate) {
  generatePoms();
}

const actual = collect();
const rendered = `${BASELINE_HEADER}\n${actual.join("\n")}\n`;

if (update) {
  writeFileSync(baselinePath, rendered);
  console.log(`Wrote ${actual.length} entries to ${baselinePath}`);
  process.exit(0);
}

if (!existsSync(baselinePath)) {
  fail(`No baseline at ${baselinePath}. Create it with --update.`);
}

const expected = readFileSync(baselinePath, "utf8")
  .split("\n")
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith("#"));

const added = actual.filter((line) => !expected.includes(line));
const removed = expected.filter((line) => !actual.includes(line));

if (added.length === 0 && removed.length === 0) {
  console.log(
    `✓ Published Android dependency scopes match ${baselinePath} (${actual.length} entries).`
  );
  process.exit(0);
}

console.error("Published Android dependency scopes changed:\n");
for (const line of removed) {
  console.error(`  - ${line}`);
}
for (const line of added) {
  console.error(`  + ${line}`);
}
fail(
  "A dependency moving to `runtime` means it left consumers' compile classpath.\n" +
    "   If any of its types appear in a public signature, declare it with `api(...)`.\n" +
    "   If the change is intentional, rerun with --update and commit the baseline."
);
